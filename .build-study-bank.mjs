import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const { renderToString } = await import(pathToFileURL(process.argv[2]));
const escapes = { "&": "&amp;", "<": "&lt;", ">": "&gt;" };

function math(tex, displayMode = false) {
  const rendered = renderToString(tex.trim(), { displayMode, output: "mathml", strict: "error" });
  return rendered.match(/<math\b[\s\S]*<\/math>/)[0].replace(/<annotation\b[\s\S]*?<\/annotation>/, "");
}

function inline(text) {
  return text.split(/(\$[^$\n]+\$|\*\*[^*\n]+\*\*)/).map(part => {
    if (part.startsWith("$") && part.endsWith("$")) return math(part.slice(1, -1));
    if (part.startsWith("**") && part.endsWith("**")) return "<strong>" + inline(part.slice(2, -2)) + "</strong>";
    return part.replace(/[&<>]/g, character => escapes[character]);
  }).join("");
}

function answerHtml(markdown) {
  return markdown.replace(/^\*\*Ответ\.\*\*\s*/, "").trim()
    .split(/(\$\$[\s\S]+?\$\$)|\n{2,}/).filter(part => part?.trim())
    .map(part => {
      if (part.startsWith("$$")) return '<div class="formula">' + math(part.slice(2, -2), true) + "</div>";
      if (part.startsWith("- ")) {
        return "<ul>" + part.split("\n").map(line => "<li>" + inline(line.slice(2)) + "</li>").join("") + "</ul>";
      }
      return "<p>" + inline(part) + "</p>";
    }).join("");
}

const questionBank = [];
for (const [index, choices] of distractors.entries()) {
  const survey = index + 1;
  const md = readFileSync(new URL("./Опрос " + survey + " — вопросы и ответы.md", import.meta.url), "utf8")
    .replace(/\r\n/g, "\n");
  let topic;
  let number = 0;
  const sections = md.split(/^(#{2,3} .+)$/gm);
  for (let section = 1; section < sections.length; section += 2) {
    const heading = sections[section];
    if (heading.startsWith("## ")) {
      topic = heading.slice(3);
      continue;
    }
    const [, marker, prompt] = heading.match(/^### (\d+)\. (.+)$/);
    if (Number(marker) !== ++number || !choices[number - 1]) throw Error("Unexpected question " + heading);
    questionBank.push({
      survey,
      number,
      topic,
      prompt: inline(prompt),
      answer: answerHtml(sections[section + 1].trim()),
      choices: choices[number - 1],
    });
  }
  if (number !== choices.length) throw Error("Question count mismatch");
}
const lines = questionBank.map(question => "  " + JSON.stringify(question));
